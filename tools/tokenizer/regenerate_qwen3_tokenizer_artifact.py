"""tools/tokenizer/regenerate_qwen3_tokenizer_artifact.py -- TE-92: regenerates
the ratified candidate's converter-emitted TOKENIZER ARTIFACT
(`Claude/Plans/SuperEmbedder_Plan.md` sec 7's E0b row: "a real,
converter-emitted tokenizer artifact") from the pinned SuperSLM tag's own
`tools/convert_tokenizer.py`, and holds the result to the committed
manifest `tests/fixtures/tokenizer/qwen3-embedding-0.6b-tokenizer.manifest.json`.

THE ARTIFACT IS NEVER COMMITTED. It is 3.4 MB of bytes derived from the
checkpoint's tokenizer.json, regenerable bit-for-bit from two inputs this
script pins: the engine tag in `superslm.lock` (whose converter is the
algorithm) and the HF snapshot directory (whose tokenizer.json +
tokenizer_config.json are the data). The manifest carries the SHA-256 the
regenerated bytes must equal; a mismatch is refused by name, never
re-minted here.

MODES
  (default)   clone the pinned tag, run `convert_tokenizer.py --emit`, write
              the artifact to --out, compare its SHA-256 and size to the
              manifest (exit 3 on mismatch). Needs only the checkpoint's two
              JSON files and the engine's Python tools (stdlib + numpy);
              transformers is NOT needed.
  --verify    additionally run the converter's TWO parity modes against the
              upstream HF tokenizer over the committed 44-record corpus
              (`--verify` = BPE/tokenization parity, add_special_tokens=False;
              `--verify-post-processor` = post-processor parity,
              add_special_tokens=True, trailing_special_id=151643). Needs
              `transformers`. Exit 4 on any mismatch or a non-zero converter
              exit.
  --mint      write the manifest from this run instead of grading against
              it (a minting run grades nothing); records the exact command,
              the checkpoint revision and tokenizer.json SHA-256, the converter
              commit, the artifact SHA-256/size, and -- when --verify is also
              given -- the two verification results.

USAGE
  python tools/tokenizer/regenerate_qwen3_tokenizer_artifact.py \\
      --snapshot D:/hf_cache/hub/models--Qwen--Qwen3-Embedding-0.6B/snapshots/97b0c614be4d77ee51c0cef4e5f07c00f9eb65b3 \\
      --out build/_scratch/qwen3-embedding-0.6b-tokenizer.sslm [--verify] [--mint]
      [--lock superslm.lock] [--source <path-or-url>] [--workdir <scratch dir>]

Exit codes: 0 regenerated and matching (and verified, if asked); 1 usage/
environment; 2 clone/emit failure; 3 artifact does not match the manifest;
4 a parity mode failed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import stat
import subprocess
import sys
import time
from pathlib import Path

DEFAULT_REMOTE = "https://github.com/dansupergameprogrammer/SuperSLM.git"
REPO_ROOT = Path(__file__).resolve().parent.parent.parent
FIXTURES = REPO_ROOT / "tests" / "fixtures" / "tokenizer"
MANIFEST = FIXTURES / "qwen3-embedding-0.6b-tokenizer.manifest.json"
CORPUS = FIXTURES / "tokenizer_golden_corpus.jsonl"
CANDIDATE_REPO = "Qwen/Qwen3-Embedding-0.6B"
CANDIDATE_REVISION = "97b0c614be4d77ee51c0cef4e5f07c00f9eb65b3"
EXPECTED_TRAILING_SPECIAL_ID = 151643


def _rmtree_onerror(func, path, exc_info):
    os.chmod(path, stat.S_IWRITE)
    func(path)


def rmtree(p: Path) -> None:
    if p.exists():
        shutil.rmtree(p, onerror=_rmtree_onerror)


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def read_lock(lock_path: Path) -> dict:
    out = {}
    for line in lock_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            out[k] = v
    return out


def clone_engine(tag: str, source: str, workdir: Path) -> Path:
    rmtree(workdir)
    workdir.mkdir(parents=True)
    subprocess.run(
        ["git", "clone", "-c", "core.autocrlf=false", "-c", "core.eol=lf",
         "--branch", tag, "--single-branch", source, str(workdir)],
        check=True, capture_output=True, text=True,
    )
    return workdir


def main(argv: list) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--snapshot", required=True, help="the pinned HF snapshot directory")
    ap.add_argument("--out", required=True, help="where to write the regenerated tokenizer .sslm")
    ap.add_argument("--lock", default=str(REPO_ROOT / "superslm.lock"))
    ap.add_argument("--source", default=DEFAULT_REMOTE)
    ap.add_argument("--workdir", default=str(REPO_ROOT / "build" / "_tokenizer_artifact_workdir"))
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--mint", action="store_true")
    args = ap.parse_args(argv)

    snapshot = Path(args.snapshot)
    tok_json = snapshot / "tokenizer.json"
    tok_cfg = snapshot / "tokenizer_config.json"
    if not tok_json.exists() or not tok_cfg.exists():
        print(f"SEMB_TOKENIZER_SNAPSHOT_MISSING: {snapshot} lacks tokenizer.json/tokenizer_config.json",
              file=sys.stderr)
        return 1
    if snapshot.name != CANDIDATE_REVISION:
        print(f"SEMB_TOKENIZER_REVISION_MISMATCH: snapshot directory is {snapshot.name!r}, "
              f"the pinned revision is {CANDIDATE_REVISION}", file=sys.stderr)
        return 1
    lock = read_lock(Path(args.lock))
    tag = lock.get("tag", "")
    if not tag:
        print(f"SEMB_FIXTURE_LOCK_MISSING: {args.lock} has no tag= line", file=sys.stderr)
        return 1
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else None
    if manifest is None and not args.mint:
        print(f"SEMB_TOKENIZER_MANIFEST_MISSING: {MANIFEST} (run with --mint to create it)", file=sys.stderr)
        return 1

    workdir = Path(args.workdir)
    try:
        clone = clone_engine(tag, args.source, workdir)
    except subprocess.CalledProcessError as ex:
        print(f"SEMB_FIXTURE_CLONE_FAILED: {ex.stderr}", file=sys.stderr)
        return 2
    converter_commit = subprocess.run(["git", "-C", str(clone), "rev-parse", "HEAD"],
                                      capture_output=True, text=True, check=True).stdout.strip()
    tools = clone / "tools"
    # Absolute: the converter runs with the clone's tools/ as its cwd.
    out = Path(args.out).resolve()
    out.parent.mkdir(parents=True, exist_ok=True)

    emit_cmd = [sys.executable, "convert_tokenizer.py", "--ckpt", str(snapshot), "--emit", str(out)]
    t0 = time.perf_counter()
    emit = subprocess.run(emit_cmd, cwd=tools, capture_output=True, text=True)
    emit_s = time.perf_counter() - t0
    if emit.returncode != 0 or not out.exists():
        print(f"SEMB_TOKENIZER_EMIT_FAILED (exit {emit.returncode}):\n{emit.stdout}\n{emit.stderr}",
              file=sys.stderr)
        rmtree(workdir)
        return 2
    art_sha = sha256_file(out)
    art_bytes = out.stat().st_size
    print(f"emitted {out}: {art_bytes} bytes sha256={art_sha} in {emit_s:.1f}s\n{emit.stdout.strip()}")

    verify_result = None
    if args.verify:
        ver_cmd = [sys.executable, "convert_tokenizer.py", "--ckpt", str(snapshot),
                   "--verify", str(CORPUS), "--verify-post-processor", str(CORPUS)]
        ver = subprocess.run(ver_cmd, cwd=tools, capture_output=True, text=True)
        text = ver.stdout + ver.stderr
        print(text.strip())
        bpe_ok = f"{sum(1 for l in CORPUS.read_text(encoding='utf-8').splitlines() if l)} lines, 0 mismatches" in text
        pp_ok = ("post-processor-parity:" in text and " 0 mismatches" in text.split("post-processor-parity:")[-1]
                 and f"trailing_special_id={EXPECTED_TRAILING_SPECIAL_ID}" in text)
        verify_result = {
            "command": " ".join(ver_cmd),
            "exit_code": ver.returncode,
            "bpe_parity": "PASS" if bpe_ok else "FAIL",
            "post_processor_parity": "PASS" if pp_ok else "FAIL",
            "trailing_special_id": EXPECTED_TRAILING_SPECIAL_ID,
            "stdout": text.strip().splitlines(),
        }
        if ver.returncode != 0 or not (bpe_ok and pp_ok):
            print("SEMB_TOKENIZER_PARITY_FAILED", file=sys.stderr)
            rmtree(workdir)
            return 4
    rmtree(workdir)

    if args.mint:
        record = {
            "schema": "semb_tokenizer_artifact_manifest_v1",
            "minted": time.strftime("%Y-%m-%d"),
            "minted_by": "tools/tokenizer/regenerate_qwen3_tokenizer_artifact.py --mint",
            "artifact": {"name": out.name, "sha256": art_sha, "bytes": art_bytes},
            "checkpoint": {
                "repo": CANDIDATE_REPO,
                "revision": CANDIDATE_REVISION,
                "tokenizer_json_sha256": sha256_file(tok_json),
                "tokenizer_config_json_sha256": sha256_file(tok_cfg),
            },
            "converter": {
                "tool": "tools/convert_tokenizer.py",
                "engine_tag": tag,
                "engine_commit": lock.get("commit", ""),
                "clone_head": converter_commit,
                "emit_command": " ".join(emit_cmd),
            },
            "verification": verify_result,
            "corpus": {"path": "tests/fixtures/tokenizer/tokenizer_golden_corpus.jsonl",
                       "sha256": sha256_file(CORPUS)},
        }
        MANIFEST.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8", newline="\n")
        print(f"MINTED {MANIFEST}")
        return 0

    want = manifest["artifact"]
    if want["sha256"] != art_sha or want["bytes"] != art_bytes:
        print(f"SEMB_TOKENIZER_ARTIFACT_MISMATCH: regenerated sha256={art_sha} bytes={art_bytes}; "
              f"manifest sha256={want['sha256']} bytes={want['bytes']}", file=sys.stderr)
        return 3
    if manifest["converter"]["engine_tag"] != tag or manifest["converter"]["clone_head"] != converter_commit:
        print(f"SEMB_TOKENIZER_CONVERTER_MISMATCH: manifest converter {manifest['converter']['engine_tag']}@"
              f"{manifest['converter']['clone_head']}, this run {tag}@{converter_commit}", file=sys.stderr)
        return 3
    print(f"MATCH: {out.name} sha256={art_sha} bytes={art_bytes} == manifest; converter {tag}@{converter_commit}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
